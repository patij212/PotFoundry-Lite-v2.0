// prior refutations point to:
//   (1) SMOOTH GRADING — replace the abrupt dense↔coarse transition by grading the size ratio between neighbours
//       (gradeBeta-limited). Here we do NOT re-seed (the CONFIRMED mesh already holds fidelity); instead the
//       relaxation itself smooths the transition because it moves points toward locally-uniform mm-spacing, which
//       spreads the abrupt pitch jump into a graded ramp. (A pure re-seed arm is a SEPARATE experiment.)
//   (2) SURFACE-PRESERVING LAPLACIAN-UNDER-M relaxation — iterate FREE (non-crest, non-boundary) vertices toward
//       their M-metric-equilateral (area/angle-optimal) position in the mm-scaled (u,t) chart, RE-PROJECT onto the
//       true analytic surface (trivial: any (u,t) lifts on-surface by construction), and REJECT the move if it
//       makes any incident triangle's honest interior deviation exceed tol (the outlier-hold guard — this is why
//       relaxation succeeds where the a-posteriori Lawson FLIPS of E-…-TIERAB-SLIVERS §3b failed: flips reconnect
//       the SAME needle point set and cannot escape it; relaxation MOVES the points).
//
// THE M=g/h² CHART: mesh in (u,t); the mm-scaled chart is (x=u·arcPerU, y=t·H). On the mean surface this chart is
// arc-length-faithful, so a uniform (mm-space) Laplacian IS the metric-equilateral move to first order. On the
// near-vertical near-crest flank (su≫arcPerU) the mm-chart under-states the true 3D stretch — that is EXACTLY where
// the reject-guard fires (a move that flattens a needle there would over-chord the flank), so fidelity is held by
// the honest brute, not by the chart. This is the correct division of labour: Laplacian for quality, brute for
// fidelity.
//
